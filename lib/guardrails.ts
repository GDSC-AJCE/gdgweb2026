/**
 * GDG AJCE Guardrails Engine
 * Comprehensive safety, validation, and security guardrails for AI agent workflows,
 * user prompts, and Gemini-powered generation.
 */

export interface GuardrailCheckResult {
  isValid: boolean;
  score?: number;
  violations: string[];
  sanitizedText?: string;
  metadata?: Record<string, unknown>;
}

// Common prompt injection and jailbreak signatures
const PROMPT_INJECTION_PATTERNS = [
  /ignore\s+(all\s+)?(previous|prior|above)\s+(instructions|prompts|rules)/i,
  /disregard\s+(all\s+)?(previous|prior)\s+directives/i,
  /you\s+are\s+now\s+in\s+(developer|dan|jailbreak)\s+mode/i,
  /system\s+override\s*:/i,
  /bypass\s+(safety|content)\s+filters/i,
  /reveal\s+(system\s+prompt|hidden\s+instructions|api\s+keys)/i,
  /repeat\s+(everything|the\s+prompt)\s+above/i,
  /<script\b[^<]*(?:(?!<\/script>)<[^<]*)*<\/script>/gi,
];

// Sensitive credential and secret patterns
const SENSITIVE_PATTERNS = [
  /AIza[0-9A-Za-z-_]{35}/g, // Google API Key
  /(?:firebase|private[_-]?key|secret[_-]?token)\s*[:=]\s*['"][^'"]+['"]/gi,
  /Bearer\s+[A-Za-z0-9\-._~+/]+=*/g,
];

/**
 * Validates text against prompt injection, jailbreaks, and malicious instructions.
 */
export function validatePromptGuardrails(input: string): GuardrailCheckResult {
  const violations: string[] = [];

  if (!input || typeof input !== "string") {
    return {
      isValid: false,
      violations: ["Input must be a non-empty string"],
    };
  }

  // Length check (prevent DOS token flooding)
  if (input.length > 32000) {
    violations.push("Prompt exceeds maximum permissible length (32,000 characters)");
  }

  // Check injection patterns
  for (const pattern of PROMPT_INJECTION_PATTERNS) {
    if (pattern.test(input)) {
      violations.push(`Prompt contains forbidden injection or jailbreak pattern: ${pattern.toString()}`);
    }
  }

  // Check secret leaks in prompt
  for (const pattern of SENSITIVE_PATTERNS) {
    if (pattern.test(input)) {
      violations.push("Prompt contains potential API key or secret token");
    }
  }

  return {
    isValid: violations.length === 0,
    violations,
    sanitizedText: violations.length === 0 ? sanitizeInput(input) : undefined,
  };
}

/**
 * Strips dangerous HTML tags and script elements from input text.
 */
export function sanitizeInput(text: string): string {
  if (!text) return "";
  return text
    .replace(/<script\b[^<]*(?:(?!<\/script>)<[^<]*)*<\/script>/gi, "")
    .replace(/javascript:/gi, "")
    .replace(/on\w+\s*=/gi, "")
    .trim();
}

/**
 * Redacts or masks Personally Identifiable Information (PII) and secret keys.
 */
export function maskSensitiveData(text: string): string {
  if (!text) return "";
  let masked = text;

  // Mask API Keys
  masked = masked.replace(/AIza[0-9A-Za-z-_]{35}/g, "AIza***************************");

  // Mask Phone numbers (E.164 or common Indian/International formats)
  masked = masked.replace(/(\+?91[\-\s]?)?[6789]\d{9}/g, "[PHONE_REDACTED]");

  // Mask Credit Cards
  masked = masked.replace(/\b(?:\d{4}[-\s]?){3}\d{4}\b/g, "[CARD_REDACTED]");

  return masked;
}

