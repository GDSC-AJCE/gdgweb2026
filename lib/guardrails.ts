/**
 * Validates output generated by an LLM agent before presenting to users or committing to Firestore.
 */
export function validateAgentOutput(output: string): GuardrailCheckResult {
  const violations: string[] = [];

  if (!output || typeof output !== "string") {
    return { isValid: false, violations: ["Output is empty or not a string"] };
  }

  // Detect inadvertent secret exposure in generated output
  for (const pattern of SENSITIVE_PATTERNS) {
    if (pattern.test(output)) {
      violations.push("Generated output contained sensitive credentials or internal tokens");
    }
  }

  return {
    isValid: violations.length === 0,
    violations,
    sanitizedText: maskSensitiveData(output),
  };
}

/**
 * Validates student or member email address domain for campus access.
 */
export function validateCampusDomainGuardrail(email: string): boolean {
  if (!email || !email.includes("@")) return false;
  const domain = email.split("@")[1].toLowerCase();
  // Validates Amal Jyothi official domain or approved educational accounts
  return domain === "amaljyothi.ac.in" || domain.endsWith(".amaljyothi.ac.in");
}
